import { describe, expect, it } from 'bun:test'
import { mkdtempSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

import { findPages, generatePages, inertiaPages, pagesDeclaration } from '../src/vite-entry'

const fixture = () => {
	const root = mkdtempSync(join(tmpdir(), 'inertia-pages-'))
	const dir = join(root, 'pages')
	mkdirSync(join(dir, 'users'), { recursive: true })
	for (const file of ['users/index.tsx', 'users/show.vue', 'home.tsx', 'home.vue', 'notes.md', 'types.d.ts'])
		writeFileSync(join(dir, file), '')
	return { dir, dts: join(root, 'types', 'inertia-pages.d.ts') }
}

describe('page discovery', () => {
	it('finds page components by name', () => {
		const { dir } = fixture()
		expect(findPages({ dir })).toEqual(['home', 'users/index', 'users/show'])
		expect(findPages({ dir: join(dir, 'missing') })).toEqual([])
	})

	it('writes the declaration only when pages change', () => {
		const options = fixture()
		expect(generatePages(options)).toBe(true)
		expect(readFileSync(options.dts, 'utf8')).toContain('"users/show": true')
		expect(generatePages(options)).toBe(false)

		// A CRLF checkout of the same declaration is not a change
		writeFileSync(options.dts, readFileSync(options.dts, 'utf8').replace(/\n/g, '\r\n'))
		expect(generatePages(options)).toBe(false)

		writeFileSync(join(options.dir, 'about.tsx'), '')
		expect(generatePages(options)).toBe(true)
		expect(readFileSync(options.dts, 'utf8')).toContain('"about": PropsOf<typeof import("../pages/about").default>')
	})

	it('reads each page’s props from its default export', () => {
		const options = fixture()
		writeFileSync(join(options.dir, 'about.jsx'), '')
		expect(pagesDeclaration(options)).toBe(`// Generated by elysia-inertia from your page files. Do not edit.
import type { PropsOf } from 'elysia-inertia'

declare module 'elysia-inertia' {
	interface InertiaPages {
		"about": PropsOf<typeof import("../pages/about").default>
		"home": true
		"users/index": PropsOf<typeof import("../pages/users/index").default>
		"users/show": true
	}
}
`)
	})

	it('regenerates in dev when a page is added or removed', () => {
		const options = fixture()
		const listeners: ((file: string) => void)[] = []
		const plugin = inertiaPages({ dir: 'pages', dts: 'types/inertia-pages.d.ts' })
		plugin.configResolved({ root: join(options.dir, '..') })
		plugin.buildStart()
		plugin.configureServer({ watcher: { on: (_event, listener) => listeners.push(listener) } })

		const page = join(options.dir, 'settings.tsx')
		writeFileSync(page, '')
		for (const listener of listeners) listener(page)
		expect(readFileSync(options.dts, 'utf8')).toContain('"settings": PropsOf<')
	})

	it('warns when no pages are found', () => {
		const warn = console.warn
		const messages: string[] = []
		console.warn = (message: string) => messages.push(message)
		try {
			const { dir, dts } = fixture()
			generatePages({ dir: join(dir, 'missing'), dts })
		} finally {
			console.warn = warn
		}
		expect(messages[0]).toContain('No pages found')
	})

	it('keeps the type-test fixture in sync', () => {
		const dts = join(import.meta.dir, 'pages-types/inertia-pages.d.ts')
		expect(readFileSync(dts, 'utf8')).toBe(
			pagesDeclaration({ dir: join(import.meta.dir, 'pages-types/pages'), dts })
		)
	})
})
