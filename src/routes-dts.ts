import { writeIfChanged } from './pages.js'

/** The `InertiaRoutes` declaration for these route paths */
export const routesDeclaration = (paths: string[]) =>
	`// Generated by elysia-inertia from the app's routes. Do not edit.
declare module 'elysia-inertia' {
	interface InertiaRoutes {
${paths.map((path) => `\t\t${JSON.stringify(path)}: true`).join('\n')}
	}
}

export {}
`

/**
 * Write the app's GET routes as `InertiaRoutes`, so `inertia.redirect()`
 * checks paths and params. `inertia({ routes })` calls it when the server
 * starts in dev; call it yourself from a script otherwise. Returns whether
 * the file changed
 */
export const writeRoutes = (
	app: { routes: { method: string; path: string }[] },
	dts = 'inertia-routes.d.ts'
) => {
	const paths = [
		...new Set(app.routes.filter((route) => route.method === 'GET').map((route) => route.path))
	].sort()

	return writeIfChanged(dts, routesDeclaration(paths))
}
