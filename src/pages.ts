import {
	existsSync,
	mkdirSync,
	readdirSync,
	readFileSync,
	writeFileSync
} from 'node:fs'
import { dirname, join, relative, resolve, sep } from 'node:path'

export interface PagesOptions {
	/** Folder holding the page components (default `src/pages`) */
	dir?: string
	/** Page file extensions (default `.tsx .jsx .vue .svelte`) */
	extensions?: string[]
	/**
	 * Declaration file to write; include it in the server's tsconfig
	 * (default `inertia-pages.d.ts`)
	 */
	dts?: string
	/**
	 * File checking each `.tsx` page's default export against its routes'
	 * props, or `false` (default `inertia-pages.check.ts`). Needs `Register`
	 */
	check?: string | false
}

const defaults = {
	dir: 'src/pages',
	extensions: ['.tsx', '.jsx', '.vue', '.svelte'],
	dts: 'inertia-pages.d.ts',
	check: 'inertia-pages.check.ts' as string | false
}

/** Extensions `tsc` can type a page's default export from */
const CHECKED = ['.tsx', '.ts']

const walk = (dir: string): string[] =>
	readdirSync(dir, { withFileTypes: true }).flatMap((entry) =>
		entry.isDirectory()
			? walk(join(dir, entry.name))
			: entry.isFile()
				? [join(dir, entry.name)]
				: []
	)

interface PageFile {
	name: string
	file: string
	extension: string
}

const scanPages = (options: PagesOptions): PageFile[] => {
	const { dir, extensions } = { ...defaults, ...options }
	if (!existsSync(dir)) return []

	return walk(dir).flatMap((file) => {
		const extension = extensions.find((ext) => file.endsWith(ext))
		if (!extension || file.endsWith(`.d${extension}`)) return []

		const name = relative(dir, file).slice(0, -extension.length).split(sep).join('/')
		return [{ name, file, extension }]
	})
}

/** Component names under `dir`: `users/index.tsx` → `users/index` */
export const findPages = (options: PagesOptions = {}) =>
	// `home.tsx` and `home.vue` are one page name
	[...new Set(scanPages(options).map((page) => page.name))].sort()

export const pagesDeclaration = (pages: string[]) =>
	`// Generated by elysia-inertia from your page files. Do not edit.
declare module 'elysia-inertia' {
	interface InertiaPages {
${pages.map((page) => `\t\t${JSON.stringify(page)}: true`).join('\n')}
	}
}

export {}
`

/**
 * Check each page file's default export against the props its routes
 * render. Written as `.ts`, since `skipLibCheck` would skip a `.d.ts`
 */
export const pagesCheck = (pages: { name: string; file: string }[], check: string) => {
	const from = dirname(resolve(check))
	const lines = pages.map(({ name, file }, index) => {
		const path = relative(from, resolve(file)).split(sep).join('/').replace(/\.tsx?$/, '')
		const specifier = path.startsWith('.') ? path : `./${path}`
		// Exported so `noUnusedLocals` doesn't flag them
		return `export type _${index} = CheckPage<${JSON.stringify(name)}, typeof import(${JSON.stringify(specifier)}).default>`
	})

	return `// Generated by elysia-inertia: each page must accept the props its
// routes render. Do not edit.
import type { CheckPage } from 'elysia-inertia/client'

${lines.join('\n')}
`
}

// Git may check a committed file out with CRLF; that is not a change
const writeIfChanged = (file: string, content: string) => {
	if (existsSync(file) && readFileSync(file, 'utf8').replace(/\r\n/g, '\n') === content)
		return false

	mkdirSync(dirname(resolve(file)), { recursive: true })
	writeFileSync(file, content)
	return true
}

/**
 * Write the `InertiaPages` declaration for the pages on disk, so
 * `render('users/index')` is checked against real files, and the page
 * check file. Returns whether either changed
 */
export const generatePages = (options: PagesOptions = {}) => {
	const { dir, dts, check } = { ...defaults, ...options }
	const pages = findPages(options)
	// An empty InertiaPages turns name checking off, so say why
	if (!pages.length)
		console.warn(`[inertia] No pages found in ${resolve(dir)}; page names are not checked`)

	const changed = writeIfChanged(dts, pagesDeclaration(pages))
	if (check === false) return changed

	const checked = new Map<string, PageFile>()
	for (const page of scanPages(options))
		if (CHECKED.includes(page.extension) && !checked.has(page.name)) checked.set(page.name, page)
	const sorted = [...checked.values()].sort((a, b) => (a.name < b.name ? -1 : 1))

	return writeIfChanged(check, pagesCheck(sorted, check)) || changed
}

/** The part of Vite's dev server the plugin uses */
interface DevServer {
	watcher: { on(event: 'add' | 'unlink', listener: (file: string) => void): unknown }
}

/**
 * Vite plugin: keeps the `InertiaPages` declaration in sync with the page
 * folder, on build and while the dev server runs
 *
 * ```ts
 * // vite.config.ts
 * import { inertiaPages } from 'elysia-inertia/vite'
 *
 * export default defineConfig({ plugins: [inertiaPages({ dir: 'src/pages' })] })
 * ```
 */
export const inertiaPages = (options: PagesOptions = {}) => {
	// Relative paths follow Vite's root, like the rest of its config
	let resolved = { ...defaults, ...options }
	const generate = () => generatePages(resolved)

	return {
		name: 'elysia-inertia:pages',
		configResolved(config: { root: string }) {
			resolved = {
				...resolved,
				dir: resolve(config.root, resolved.dir),
				dts: resolve(config.root, resolved.dts),
				check: resolved.check && resolve(config.root, resolved.check)
			}
		},
		buildStart() {
			generate()
		},
		configureServer(server: DevServer) {
			const update = (file: string) => {
				if (resolve(file).startsWith(resolve(resolved.dir) + sep)) generate()
			}
			server.watcher.on('add', update)
			server.watcher.on('unlink', update)
		}
	}
}
