import {
	existsSync,
	mkdirSync,
	readdirSync,
	readFileSync,
	writeFileSync
} from 'node:fs'
import { dirname, join, relative, resolve, sep } from 'node:path'

export interface PagesOptions {
	/** Folder holding the page components (default `src/pages`) */
	dir?: string
	/** Page file extensions (default `.tsx .jsx .vue .svelte`) */
	extensions?: string[]
	/**
	 * Declaration file to write; include it in the server's tsconfig
	 * (default `inertia-pages.d.ts`)
	 */
	dts?: string
}

const defaults = {
	dir: 'src/pages',
	extensions: ['.tsx', '.jsx', '.vue', '.svelte'],
	dts: 'inertia-pages.d.ts'
}

const walk = (dir: string): string[] =>
	readdirSync(dir, { withFileTypes: true }).flatMap((entry) =>
		entry.isDirectory()
			? walk(join(dir, entry.name))
			: entry.isFile()
				? [join(dir, entry.name)]
				: []
	)

/** Component names under `dir`: `users/index.tsx` → `users/index` */
export const findPages = (options: PagesOptions = {}) => {
	const { dir, extensions } = { ...defaults, ...options }
	if (!existsSync(dir)) return []

	const names = walk(dir).flatMap((file) => {
		const extension = extensions.find((ext) => file.endsWith(ext))
		if (!extension || file.endsWith(`.d${extension}`)) return []

		return [relative(dir, file).slice(0, -extension.length).split(sep).join('/')]
	})

	// `home.tsx` and `home.vue` are one page name
	return [...new Set(names)].sort()
}

export const pagesDeclaration = (pages: string[]) =>
	`// Generated by elysia-inertia from your page files. Do not edit.
declare module 'elysia-inertia' {
	interface InertiaPages {
${pages.map((page) => `\t\t${JSON.stringify(page)}: true`).join('\n')}
	}
}

export {}
`

/**
 * Write the `InertiaPages` declaration for the pages on disk, so
 * `render('users/index')` is checked against real files. Returns whether
 * the file changed
 */
export const generatePages = (options: PagesOptions = {}) => {
	const { dir, dts } = { ...defaults, ...options }
	const pages = findPages(options)
	// An empty InertiaPages turns name checking off, so say why
	if (!pages.length)
		console.warn(`[inertia] No pages found in ${resolve(dir)}; page names are not checked`)

	const content = pagesDeclaration(pages)
	// Git may check the committed file out with CRLF; that is not a change
	if (existsSync(dts) && readFileSync(dts, 'utf8').replace(/\r\n/g, '\n') === content)
		return false

	mkdirSync(dirname(resolve(dts)), { recursive: true })
	writeFileSync(dts, content)
	return true
}

/** The part of Vite's dev server the plugin uses */
interface DevServer {
	watcher: { on(event: 'add' | 'unlink', listener: (file: string) => void): unknown }
}

/**
 * Vite plugin: keeps the `InertiaPages` declaration in sync with the page
 * folder, on build and while the dev server runs
 *
 * ```ts
 * // vite.config.ts
 * import { inertiaPages } from 'elysia-inertia/vite'
 *
 * export default defineConfig({ plugins: [inertiaPages({ dir: 'src/pages' })] })
 * ```
 */
export const inertiaPages = (options: PagesOptions = {}) => {
	// Relative paths follow Vite's root, like the rest of its config
	let resolved = { ...defaults, ...options }
	const generate = () => generatePages(resolved)

	return {
		name: 'elysia-inertia:pages',
		configResolved(config: { root: string }) {
			resolved = {
				...resolved,
				dir: resolve(config.root, resolved.dir),
				dts: resolve(config.root, resolved.dts)
			}
		},
		buildStart() {
			generate()
		},
		configureServer(server: DevServer) {
			const update = (file: string) => {
				if (resolve(file).startsWith(resolve(resolved.dir) + sep)) generate()
			}
			server.watcher.on('add', update)
			server.watcher.on('unlink', update)
		}
	}
}
