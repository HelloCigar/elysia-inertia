import {
	existsSync,
	mkdirSync,
	readdirSync,
	readFileSync,
	writeFileSync
} from 'node:fs'
import { dirname, join, relative, resolve, sep } from 'node:path'

export interface PagesOptions {
	/** Folder holding the page components (default `src/pages`) */
	dir?: string
	/** Page file extensions (default `.tsx .jsx .vue .svelte`) */
	extensions?: string[]
	/**
	 * Declaration file to write; include it in the server's tsconfig
	 * (default `inertia-pages.d.ts`)
	 */
	dts?: string
}

const defaults = {
	dir: 'src/pages',
	extensions: ['.tsx', '.jsx', '.vue', '.svelte'],
	dts: 'inertia-pages.d.ts'
}

/**
 * Extensions `tsc` reads a page's props from. JavaScript pages need
 * `allowJs`, so they are name only
 */
const TYPED = ['.tsx', '.ts']

const walk = (dir: string): string[] =>
	readdirSync(dir, { withFileTypes: true }).flatMap((entry) =>
		entry.isDirectory()
			? walk(join(dir, entry.name))
			: entry.isFile()
				? [join(dir, entry.name)]
				: []
	)

interface PageFile {
	name: string
	file: string
	extension: string
}

const scanPages = (options: PagesOptions): PageFile[] => {
	const { dir, extensions } = { ...defaults, ...options }
	if (!existsSync(dir)) return []

	return walk(dir).flatMap((file) => {
		const extension = extensions.find((ext) => file.endsWith(ext))
		if (!extension || file.endsWith(`.d${extension}`)) return []

		const name = relative(dir, file).slice(0, -extension.length).split(sep).join('/')
		return [{ name, file, extension }]
	})
}

/** Component names under `dir`: `users/index.tsx` → `users/index` */
export const findPages = (options: PagesOptions = {}) =>
	// `home.tsx` and `home.vue` are one page name
	[...new Set(scanPages(options).map((page) => page.name))].sort()

// `.js` resolves to the `.ts`/`.tsx` source under every moduleResolution,
// where `node16`/`nodenext` reject a path without an extension
const specifier = (file: string, from: string) => {
	const path = relative(dirname(resolve(from)), resolve(file))
		.split(sep)
		.join('/')
		.replace(/\.tsx?$/, '.js')
	return path.startsWith('.') ? path : `./${path}`
}

/**
 * The `InertiaPages` declaration: each page's props from its default
 * export's type, or `true` (name only) for pages `tsc` can't read, like
 * `.vue`, `.svelte` and JavaScript. A name with files in several formats is name only
 */
export const pagesDeclaration = (options: PagesOptions = {}) => {
	const { dts } = { ...defaults, ...options }
	const byName = new Map<string, PageFile[]>()
	for (const page of scanPages(options)) byName.set(page.name, [...(byName.get(page.name) ?? []), page])

	const lines = [...byName.keys()].sort().map((name) => {
		const [page, ...others] = byName.get(name)!
		const typed = !others.length && TYPED.includes(page!.extension)
		return `\t\t${JSON.stringify(name)}: ${
			typed ? `PropsOf<typeof import(${JSON.stringify(specifier(page!.file, dts))}).default>` : 'true'
		}`
	})

	return `// Generated by elysia-inertia from your page files. Do not edit.
import type { PropsOf } from 'elysia-inertia'

declare module 'elysia-inertia' {
	interface InertiaPages {
${lines.join('\n')}
	}
}
`
}

// Git may check a committed file out with CRLF; that is not a change
const writeIfChanged = (file: string, content: string) => {
	if (existsSync(file) && readFileSync(file, 'utf8').replace(/\r\n/g, '\n') === content)
		return false

	mkdirSync(dirname(resolve(file)), { recursive: true })
	writeFileSync(file, content)
	return true
}

/**
 * Write the `InertiaPages` declaration for the pages on disk, so
 * `render('users/index', props)` is checked against the page's props.
 * Returns whether it changed
 */
export const generatePages = (options: PagesOptions = {}) => {
	const { dir, dts } = { ...defaults, ...options }
	// An empty InertiaPages turns checking off, so say why
	if (!findPages(options).length)
		console.warn(`[inertia] No pages found in ${resolve(dir)}; pages are not checked`)

	return writeIfChanged(dts, pagesDeclaration(options))
}

/** The part of Vite's dev server the plugin uses */
interface DevServer {
	watcher: { on(event: 'add' | 'unlink', listener: (file: string) => void): unknown }
}

/**
 * Vite plugin: keeps the `InertiaPages` declaration in sync with the page
 * folder, on build and while the dev server runs. Page props changes need
 * no regeneration: the declaration reads them from the files
 *
 * ```ts
 * // vite.config.ts
 * import { inertiaPages } from 'elysia-inertia/vite'
 *
 * export default defineConfig({ plugins: [inertiaPages({ dir: 'src/pages' })] })
 * ```
 */
export const inertiaPages = (options: PagesOptions = {}) => {
	// Relative paths follow Vite's root, like the rest of its config
	let resolved = { ...defaults, ...options }
	const generate = () => generatePages(resolved)

	return {
		name: 'elysia-inertia:pages',
		configResolved(config: { root: string }) {
			resolved = {
				...resolved,
				dir: resolve(config.root, resolved.dir),
				dts: resolve(config.root, resolved.dts)
			}
		},
		buildStart() {
			generate()
		},
		configureServer(server: DevServer) {
			const update = (file: string) => {
				if (resolve(file).startsWith(resolve(resolved.dir) + sep)) generate()
			}
			server.watcher.on('add', update)
			server.watcher.on('unlink', update)
		}
	}
}
